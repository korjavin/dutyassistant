const textCandidateChoreUsage = "Usage: /text_candidate_chore <name>\nExample: /text_candidate_chore Ivan"

// HandleTextCandidateChore handles the /text_candidate_chore admin command.
// It shows the admin the periodic chore reminder (including the LLM
// carrot-and-stick nudge) that the given participant would receive right now,
// without sending anything to the participant.
// Usage: /text_candidate_chore <name>
func (h *Handlers) HandleTextCandidateChore(m *tgbotapi.Message) (tgbotapi.MessageConfig, error) {
	slog.Info(fmt.Sprintf("[HandleTextCandidateChore] User %d (%s) triggered /text_candidate_chore", m.From.ID, m.From.FirstName))

	isAdmin, err := h.checkAdmin(m.From.ID)
	if err != nil || !isAdmin {
		return tgbotapi.NewMessage(m.Chat.ID, adminOnlyMessage), nil
	}

	userName := strings.TrimSpace(m.CommandArguments())
	if userName == "" {
		return tgbotapi.NewMessage(m.Chat.ID, textCandidateChoreUsage), nil
	}

	ctx := context.Background()
	user, err := h.Store.GetUserByName(ctx, userName)
	if err != nil {
		slog.Error(fmt.Sprintf("[HandleTextCandidateChore] Error getting user by name '%s': %v", userName, err))
		return tgbotapi.NewMessage(m.Chat.ID, "Failed to find user."), nil
	}
	if user == nil {
		return tgbotapi.NewMessage(m.Chat.ID, fmt.Sprintf("User '%s' not found.", userName)), nil
	}

	// Same source and filter as the periodic reminder, so the preview matches it.
	activeChores, err := h.Store.GetActiveChores(ctx)
	if err != nil {
		slog.Error(fmt.Sprintf("[HandleTextCandidateChore] Error getting active chores: %v", err))
		return tgbotapi.NewMessage(m.Chat.ID, genericErrorMessage), nil
	}
	var chores []*store.Chore
	for _, chore := range activeChores {
		if chore.User != nil && chore.User.ID == user.ID {
			chores = append(chores, chore)
		}
	}

	escapedName := html.EscapeString(user.FirstName)
	if len(chores) == 0 {
		msg := tgbotapi.NewMessage(m.Chat.ID, fmt.Sprintf("<b>%s</b> has no pending chores, so no reminder would be sent.", escapedName))
		msg.ParseMode = tgbotapi.ModeHTML
		return msg, nil
	}

	loc := choreLocation()
	now := TimeNow().In(loc)

	var nudger notification.ChoreNudger
	if c, ok := h.LLMClient.(*llm.Client); h.LLMClient != nil && (!ok || c != nil) {
		nudger = h.LLMClient
	}
	reminder, llmErr := notification.ComposeChoreReminder(ctx, now, nudger, chores, loc)

	var sb strings.Builder
	fmt.Fprintf(&sb, "🧪 <b>Preview</b> of the chore reminder for <b>%s</b> (not sent to them):\n\n", escapedName)
	sb.WriteString(reminder)
	sb.WriteString("\n\n— — —\n")
	switch {
	case nudger == nil:
		sb.WriteString("⚠️ LLM is not configured, this is the static fallback.\n")
	case llmErr != nil:
		fmt.Fprintf(&sb, "⚠️ LLM failed, this is the static fallback: <code>%s</code>\n", html.EscapeString(llmErr.Error()))
	default:
		sb.WriteString(llmDescription(h.LLMClient))
	}
	fmt.Fprintf(&sb, "<i>Context sent to the LLM:</i>\n<pre>%s</pre>", html.EscapeString(notification.DescribeChoreDelays(chores, now)))

	msg := tgbotapi.NewMessage(m.Chat.ID, sb.String())
	msg.ParseMode = tgbotapi.ModeHTML
	return msg, nil
}

// llmDescription names the provider and model behind the client, if known.
func llmDescription(c llm.ClientInterface) string {
	client, ok := c.(*llm.Client)
	if !ok || client == nil {
		return "🤖 Generated by the LLM.\n"
	}
	model, _, _ := client.Config()
	return fmt.Sprintf("🤖 Generated by <code>%s</code> / <code>%s</code>.\n", client.Provider(), html.EscapeString(model))
}

// choreLocation returns the configured chore timezone (CHORE_TIMEZONE,
// default Europe/Berlin).
func choreLocation() *time.Location {
	tz := os.Getenv("CHORE_TIMEZONE")
	if tz == "" {
		tz = "Europe/Berlin"
	}
	loc, err := time.LoadLocation(tz)
	if err != nil {
		return time.Local
	}
	return loc
}
